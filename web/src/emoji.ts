export const messageBytes = (text: string) =>
  new TextEncoder().encode(text).length;
export function insertEmoji(
  text: string,
  start: number,
  end: number,
  emoji: string,
) {
  let from = Math.max(0, Math.min(start, text.length)),
    to = Math.max(from, Math.min(end, text.length));
  const split = (at: number) =>
    at > 0 &&
    at < text.length &&
    /[\uD800-\uDBFF]/.test(text[at - 1]) &&
    /[\uDC00-\uDFFF]/.test(text[at]);
  if (split(from)) from--;
  if (split(to)) to++;
  return {
    text: text.slice(0, from) + emoji + text.slice(to),
    cursor: from + emoji.length,
  };
}
